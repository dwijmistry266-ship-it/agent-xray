"""Render an XRay as plain text (terminal) or standalone HTML."""

import html as html_lib
from typing import List

from . import __version__
from .analyze import ClaimFinding, XRay

BAR = "=" * 60


def _fmt_tokens(n: int) -> str:
    if n >= 1_000_000:
        return "%.2fM" % (n / 1_000_000)
    if n >= 1_000:
        return "%.1fk" % (n / 1_000)
    return str(n)


def _fmt_duration(seconds) -> str:
    if seconds is None:
        return "unknown"
    seconds = int(seconds)
    if seconds < 60:
        return "%ds" % seconds
    mins, secs = divmod(seconds, 60)
    if mins < 60:
        return "%dm %ds" % (mins, secs)
    hours, mins = divmod(mins, 60)
    return "%dh %dm" % (hours, mins)


def _section(title: str, lines: List[str]) -> List[str]:
    out = ["", title, "-" * len(title)]
    out.extend(lines)
    return out


def render_terminal(xray: XRay) -> str:
    """Render a clean sectioned plain-text report."""
    m = xray.meta
    out = [
        "agent-xray v%s  session %s" % (__version__, m.session_id),
        BAR,
    ]

    out += _section(
        "SESSION",
        [
            "project   : %s" % (m.project or "unknown"),
            "model     : %s" % (m.model or "unknown"),
            "started   : %s" % (m.started_at or "unknown"),
            "duration  : %s" % _fmt_duration(m.duration_seconds),
            "exchanges : %d user->assistant" % m.turn_count,
        ],
    )

    t = xray.token_totals
    cost_line = (
        "~$%.4f USD" % xray.estimated_cost_usd
        if xray.estimated_cost_usd is not None
        else "n/a"
    )
    out += _section(
        "TOKENS & COST",
        [
            "input       : %s" % _fmt_tokens(t["input"]),
            "output      : %s" % _fmt_tokens(t["output"]),
            "cache read  : %s" % _fmt_tokens(t["cache_read"]),
            "cache write : %s" % _fmt_tokens(t["cache_write"]),
            "total       : %s" % _fmt_tokens(sum(t.values())),
            "est. cost   : %s  (%s)" % (cost_line, xray.cost_note),
        ],
    )

    census_lines = [
        "%-16s %d" % (name, n) for name, n in xray.tool_census.items()
    ] or ["(no tool calls)"]
    census_lines.append("total tool calls: %d" % xray.total_tool_calls)
    out += _section("TOOL CENSUS", census_lines)

    file_lines = [
        "read (%d): %s" % (len(xray.read_files), ", ".join(xray.read_files) or "-"),
        "written (%d): %s"
        % (len(xray.written_files), ", ".join(xray.written_files) or "-"),
        "hot (>=3 reads): %s" % (", ".join(xray.hot_files) or "-"),
        "written but never read: %s"
        % (", ".join(xray.write_without_read) or "-"),
    ]
    out += _section("FILES", file_lines)

    cmd_lines = []
    for cmd in xray.commands:
        cmd_lines.append("[%s] (turn %d) %s" % (cmd.category, cmd.turn, cmd.command))
    out += _section("COMMANDS", cmd_lines or ["(none)"])

    claim_lines = []
    for c in xray.claims:
        claim_lines.append('"%s" (turn %d)' % (c.claim_text, c.turn))
        claim_lines.append("  -> %s" % c.evidence)
    out += _section("CLAIMS VS EVIDENCE", claim_lines or ["(no claims found)"])

    me = xray.most_expensive_turn
    blind_lines = [
        "written but never read : %s"
        % (", ".join(xray.write_without_read) or "-"),
        "turns with zero tools : %s"
        % (
            ", ".join(str(i) for i in xray.turns_without_tools)
            or "-"
        ),
        "most expensive turn   : #%d (%s tokens)"
        % (me["turn"], _fmt_tokens(me["tokens"])),
    ]
    out += _section("BLIND SPOTS", blind_lines)

    out += ["", BAR, "report generated by agent-xray — verify, don't trust"]
    return "\n".join(out)


def _esc(value) -> str:
    return html_lib.escape(str(value), quote=True)


def render_html(xray: XRay) -> str:
    """Render a single standalone dark-theme HTML file (inline CSS only)."""
    m = xray.meta
    t = xray.token_totals
    cost = (
        "~$%.4f USD" % xray.estimated_cost_usd
        if xray.estimated_cost_usd is not None
        else "n/a"
    )

    def rows(pairs):
        return "".join(
            "<tr><th>%s</th><td>%s</td></tr>" % (_esc(k), _esc(v))
            for k, v in pairs
        )

    census_rows = "".join(
        "<tr><td><code>%s</code></td><td>%d</td></tr>" % (_esc(n), c)
        for n, c in xray.tool_census.items()
    ) or '<tr><td colspan="2">no tool calls</td></tr>'

    cmd_rows = "".join(
        "<tr><td><span class='tag'>%s</span></td>"
        "<td>turn %d</td><td><code>%s</code></td></tr>"
        % (_esc(c.category), c.turn, _esc(c.command))
        for c in xray.commands
    ) or '<tr><td colspan="3">none</td></tr>'

    claim_rows = "".join(
        "<tr><td><q>%s</q><div class='muted'>turn %d</div></td>"
        "<td>%s</td></tr>" % (_esc(c.claim_text), c.turn, _esc(c.evidence))
        for c in xray.claims
    ) or '<tr><td colspan="2">no claims found</td></tr>'

    me = xray.most_expensive_turn
    body = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>agent-xray &mdash; {sid}</title>
<style>
body{{background:#0b0b0c;color:#e8e8e8;font-family:ui-monospace,Menlo,Consolas,monospace;margin:0;padding:24px}}
main{{max-width:880px;margin:0 auto}}
h1{{font-size:20px;color:#E63946}}
h2{{font-size:14px;text-transform:uppercase;letter-spacing:2px;color:#888;border-bottom:1px solid #222;padding-bottom:6px}}
section{{margin:28px 0}}
table{{width:100%;border-collapse:collapse;font-size:13px}}
th,td{{text-align:left;padding:6px 8px;border-bottom:1px solid #1c1c1e;vertical-align:top}}
th{{color:#888;font-weight:normal;width:180px}}
code{{color:#7dd3fc}}
.tag{{background:#1c1c1e;border:1px solid #333;border-radius:4px;padding:1px 8px;font-size:12px}}
.muted{{color:#888;font-size:12px}}
.warn{{color:#E63946}}
footer{{color:#555;font-size:12px;margin-top:40px}}
</style>
</head>
<body>
<main>
<h1>agent-xray <span class="muted">v{ver}</span></h1>
<p class="muted">session <code>{sid}</code></p>

<section><h2>Session</h2><table>{meta}</table></section>
<section><h2>Tokens &amp; cost</h2><table>{toks}</table></section>
<section><h2>Tool census</h2><table><tr><th>tool</th><th>calls</th></tr>{census}</table>
<p class="muted">total tool calls: {tcalls}</p></section>
<section><h2>Files</h2><table>{files}</table></section>
<section><h2>Commands</h2><table><tr><th>class</th><th>turn</th><th>command</th></tr>{cmds}</table></section>
<section><h2>Claims vs evidence</h2><table><tr><th>claim</th><th>evidence</th></tr>{claims}</table></section>
<section><h2>Blind spots</h2><table>{blind}</table></section>

<footer>report generated by agent-xray &mdash; verify, don&rsquo;t trust</footer>
</main>
</body>
</html>""".format(
        sid=_esc(m.session_id),
        ver=_esc(__version__),
        meta=rows(
            [
                ("project", m.project or "unknown"),
                ("model", m.model or "unknown"),
                ("started", m.started_at or "unknown"),
                ("duration", _fmt_duration(m.duration_seconds)),
                ("exchanges", "%d user->assistant" % m.turn_count),
            ]
        ),
        toks=rows(
            [
                ("input", _fmt_tokens(t["input"])),
                ("output", _fmt_tokens(t["output"])),
                ("cache read", _fmt_tokens(t["cache_read"])),
                ("cache write", _fmt_tokens(t["cache_write"])),
                ("total", _fmt_tokens(sum(t.values()))),
                ("est. cost", "%s (%s)" % (cost, xray.cost_note)),
            ]
        ),
        census=census_rows,
        tcalls=xray.total_tool_calls,
        files=rows(
            [
                ("read", ", ".join(xray.read_files) or "-"),
                ("written", ", ".join(xray.written_files) or "-"),
                ("hot (>=3 reads)", ", ".join(xray.hot_files) or "-"),
                (
                    "written but never read",
                    ", ".join(xray.write_without_read) or "-",
                ),
            ]
        ),
        cmds=cmd_rows,
        claims=claim_rows,
        blind=rows(
            [
                (
                    "written but never read",
                    ", ".join(xray.write_without_read) or "-",
                ),
                (
                    "turns with zero tools",
                    ", ".join(str(i) for i in xray.turns_without_tools) or "-",
                ),
                (
                    "most expensive turn",
                    "#%d (%s tokens)" % (me["turn"], _fmt_tokens(me["tokens"])),
                ),
            ]
        ),
    )
    return body
